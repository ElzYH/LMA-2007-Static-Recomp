#!/usr/bin/env python3
"""CI's guard on any runner: .github/scripts/no-game-content.sh in Python, plus the check that no
tool points into an agent's private scratch folders.

  python tools/no_game_content.py      (exit 1 with the offending paths)

The bash script stays for local use; CI runs this one since the Mac runner went off (the maintainer, 23 Oct)
and the PC's `bash` is WSL's. The rules are the script's: no tracked game files, generated code,
states, frames, captures, logs, user data or mod spaces; the committed game-blocks crate is the
placeholder, not lma-recomp's output; and no tools/ or .github/scripts/ file names a scratchpad.
"""
import os, re, subprocess, sys

BAD = re.compile(r"\.(xex|iso|mng|pe|dmp|state)$|(^|/)(LMA_full|lab|extracted|dumps|states|refs|frames|capture|userdata|mods)/"
                 r"|crates/game-blocks/parts/|(^|/)(last_run\.log|misses\.txt)$", re.I)
PRIVATE = re.compile(r"scratchpad|/tmp/claude|Temp[/\\]claude", re.I)
GB = "lma-rs/crates/game-blocks"


def git(*args):
    r = subprocess.run(["git", *args], capture_output=True, text=True, encoding="utf-8", errors="replace")
    if r.returncode != 0:
        sys.exit(f"git {' '.join(args)}: {r.stderr.strip()}")
    return r.stdout


def index_file(p):
    """A file's staged content, or None if it isn't in the index."""
    r = subprocess.run(["git", "cat-file", "-p", f":{p}"], capture_output=True, text=True, encoding="utf-8", errors="replace")
    return r.stdout if r.returncode == 0 else None


def problems(tracked, read_index):
    """Messages for game content in `tracked` paths and a generated game-blocks crate."""
    out = []
    bad = [p for p in tracked if BAD.search(p)]
    if bad:
        out.append("game content is tracked; remove it (git rm --cached) and check .gitignore:\n  " + "\n  ".join(bad))
    for f in (f"{GB}/Cargo.toml", f"{GB}/src/lib.rs"):
        if read_index(f) is None:
            out.append(f"{f} is missing: the committed game-blocks placeholder must stay (restore it from main)")
    if 'path = "parts/' in (read_index(f"{GB}/Cargo.toml") or ""):
        out.append(f"{GB}/Cargo.toml points at generated parts/; restore the placeholder and run: "
                   f"git update-index --skip-worktree {GB}/Cargo.toml {GB}/src/lib.rs")
    if "GENERATED by lma-recomp" in (read_index(f"{GB}/src/lib.rs") or ""):
        out.append(f"{GB}/src/lib.rs is generated code; restore the placeholder (see above)")
    return out


def private_paths(files):
    """tools/ and .github/scripts/ files that name an agent's scratch folder (#453)."""
    hits = []
    for p in files:
        try:
            with open(p, encoding="utf-8", errors="replace") as f:
                for n, line in enumerate(f, 1):
                    if PRIVATE.search(line):
                        hits.append(f"{p}:{n}: {line.strip()[:120]}")
        except OSError:
            pass
    return hits


def main():
    root = git("rev-parse", "--show-toplevel").strip()
    os.chdir(root)
    # -z: without it git quotes unusual names ("x/\\303\\274.state") and the patterns miss them (mac3, #839)
    tracked = [p for p in git("ls-files", "-z", "--cached").split("\0") if p]
    out = problems(tracked, index_file)
    # this file names the patterns it looks for, so it's the one file left out
    scripts = [p for p in tracked if p.startswith(("tools/", ".github/scripts/")) and os.path.basename(p) != os.path.basename(__file__)]
    hits = private_paths(scripts)
    if hits:
        out.append("a tool points into a private scratch folder:\n  " + "\n  ".join(hits))
    for m in out:
        print(f"::error::{m}")
    if not out:
        print("no game content tracked; no tool points at a private folder")
    return 1 if out else 0


if __name__ == "__main__":
    if sys.argv[1:] == ["--selftest"]:
        idx = {f"{GB}/Cargo.toml": '[dependencies]\ngb00 = { path = "stubs/gb00" }\n', f"{GB}/src/lib.rs": "// placeholder\n"}
        assert problems(["lma-rs/src/a.rs", "README.md"], idx.get) == []
        assert problems(["x/LMA_full/default.xex"], idx.get) and problems(["states/a.state"], idx.get)
        assert problems([], {**idx, f"{GB}/Cargo.toml": 'gb00 = { path = "parts/gb00" }'}.get)
        assert any("missing" in m for m in problems([], {f"{GB}/src/lib.rs": "// p"}.get))
        print("selftest ok")
        sys.exit(0)
    sys.exit(main())
