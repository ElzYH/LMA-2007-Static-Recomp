"""Generate crates/ppc/src/lookup_gen.rs from Xenia's ppc_opcode_lookup_gen.cc.

usage: python tools/gen_ppc_lookup.py <ppc_opcode_lookup_gen.cc>
Xenia is BSD-3-Clause; the generated table keeps that notice.
"""
import re
import sys

src = open(sys.argv[1]).read()
body = src[src.index("switch (ExtractBits(code, 0, 5))"):]

def expr(c):
    # (ExtractBits(code, a, b) << s)|(...)  ->  ((x(code, a, b) << s) | ...)
    c = c.replace("ExtractBits(code,", "x(code,")
    if c.count("x(code") == 1:  # single field: drop the redundant parens and "<< 0"
        c = c.strip("()").replace(" << 0", "").replace(") << 0", ")")
    return c

out = ["// Generated by tools/gen_ppc_lookup.py from Xenia's ppc_opcode_lookup_gen.cc",
       "// (Copyright Ben Vanik and Xenia contributors, BSD-3-Clause). Do not edit.",
       "",
       "#[inline]",
       "fn x(v: u32, a: u32, b: u32) -> u32 {",
       "    (v >> (31 - b)) & ((1u32 << (b - a + 1)) - 1)",
       "}",
       "",
       "/// Xenia-style mnemonic for an instruction word (record/OE variants end in `x`).",
       "#[allow(clippy::unusual_byte_groupings)]",
       "pub fn lookup(code: u32) -> Option<&'static str> {",
       "    match x(code, 0, 5) {"]
lines = body.splitlines()[1:]
i = 0
names = set()
while i < len(lines):
    l = lines[i].strip()
    m = re.match(r"case (\d+): PPC_DECODER_HIT\((\w+)\);", l)
    if m:
        out.append(f'        {m.group(1)} => return Some("{m.group(2)}"),'); names.add(m.group(2)); i += 1; continue
    m = re.match(r"case (\d+):$", l)
    if m:
        out.append(f"        {m.group(1)} => {{")
        i += 1
        while i < len(lines):
            l = lines[i].strip()
            sm = re.match(r"switch \((.*)\) \{$", l)
            if sm:
                out.append(f"            match {expr(sm.group(1))} {{")
                i += 1
                while not lines[i].strip().startswith("}"):
                    cm = re.match(r"case (0b[01]+): PPC_DECODER_HIT\((\w+)\);", lines[i].strip())
                    out.append(f'                {cm.group(1)} => return Some("{cm.group(2)}"),'); names.add(cm.group(2))
                    i += 1
                out.append("                _ => {}")
                out.append("            }")
                i += 1
                continue
            hm = re.match(r"PPC_DECODER_HIT\((\w+)\);", l)
            if hm:
                out.append(f'            return Some("{hm.group(1)}");'); names.add(hm.group(1)); i += 1; break
            if l == "PPC_DECODER_MISS;":
                out.append("            None"); i += 1; break
            i += 1
        out.append("        }")
        continue
    if l.startswith("default:"):
        break
    i += 1
out += ["        _ => None,", "    }", "}", ""]
open("crates/ppc/src/lookup_gen.rs", "w").write("\n".join(out))
print(len(names), "instructions")
